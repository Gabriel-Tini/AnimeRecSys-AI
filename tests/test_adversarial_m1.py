# SECTION 5: RecommendationResponse Disjoint-Track Invariant
# =============================================================================
class TestRecommendationResponseDisjointInvariant:
    """Stress tests on mathematical invariant S_aff ∩ S_disc = ∅."""

    def test_overlapping_id_rejected(self):
        """Any duplicate ID between affinity and discovery tracks MUST raise ValidationError."""
        aff_item = make_public_anime(42, "Steins;Gate")
        disc_item = make_public_anime(42, "Steins;Gate (Duplicate)")
        other = make_public_anime(99, "Frieren")

        with pytest.raises(ValidationError) as exc_info:
            RecommendationResponse(
                affinity_track=[aff_item, other],
                discovery_track=[disc_item],
            )
        assert "Disjoint-track invariant violated" in str(exc_info.value)

    def test_multiple_overlapping_ids_rejected(self):
        """Multiple duplicates between tracks must all trigger violation."""
        aff = [make_public_anime(1), make_public_anime(2), make_public_anime(3)]
        disc = [make_public_anime(2), make_public_anime(3), make_public_anime(4)]

        with pytest.raises(ValidationError) as exc_info:
            RecommendationResponse(
                affinity_track=aff,
                discovery_track=disc,
            )
        assert "Disjoint-track invariant violated" in str(exc_info.value)

    def test_empty_tracks_valid(self):
        """Empty tracks trivially satisfy disjoint invariant."""
        resp = RecommendationResponse(affinity_track=[], discovery_track=[])
        assert len(resp.affinity_track) == 0
        assert len(resp.discovery_track) == 0

    def test_strictly_disjoint_tracks_accepted(self):
        """Non-overlapping candidate sets must pass cleanly."""
        aff = [make_public_anime(i) for i in range(1, 9)]
        disc = [make_public_anime(i) for i in range(9, 11)]

        resp = RecommendationResponse(affinity_track=aff, discovery_track=disc)
        assert len(resp.affinity_track) == 8
        assert len(resp.discovery_track) == 2


