class TestTracebackSecretScrubbingAdversarial:
    """Stress tests on logging exception traceback scrubbing and secret containment."""

    def test_logger_exception_traceback_secrets_scrubbed(self):
        """Verify logger.exception() redacts exact secrets and Gemini API keys from tracebacks."""
        secret = "CustomSecretToken123456"
        gemini_key = "AIzaSyD_AdversarialSecretKey1234567890abcdef"
        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(logging.Formatter("%(asctime)s [%(levelname)s] %(name)s: %(message)s"))
        filter_obj = SensitiveDataFilter(exact_secrets=[secret])
        handler.addFilter(filter_obj)

        logger = logging.getLogger("test_adv_traceback_scrub")
        logger.addHandler(handler)
        logger.setLevel(logging.INFO)

        try:
            raise ValueError(f"Failed to query model with key: {gemini_key} and pass {secret}")
        except Exception:
            logger.exception("An unhandled exception occurred")

        output = stream.getvalue()
        assert secret not in output
        assert gemini_key not in output
        assert "[REDACTED_GEMINI_KEY]" in output
        assert "[REDACTED_SECRET]" in output

    def test_chained_exception_and_exception_args_scrubbed(self):
        """Verify chained exceptions have their attributes and tracebacks scrubbed."""
        secret = "ChainedSecretValue999"
        filter_obj = SensitiveDataFilter(exact_secrets=[secret])

        try:
            try:
                raise ValueError(f"Inner service error with {secret}")
            except Exception as inner_err:
                raise RuntimeError("Outer service failed") from inner_err
        except Exception:
            rec = logging.LogRecord("test", logging.ERROR, "test.py", 1, "Error", (), sys.exc_info())

        filter_obj.filter(rec)
        assert secret not in rec.exc_text
        assert "[REDACTED_SECRET]" in rec.exc_text
        assert secret not in str(rec.exc_info[1])
        if rec.exc_info[1].__cause__:
            assert secret not in str(rec.exc_info[1].__cause__)

    def test_non_string_msg_exception_logging(self):
        """Verify logging an Exception object directly as msg is sanitized."""
        gemini_key = "AIzaSyA_NonStringMsgKey1234567890abcdef"
        stream = io.StringIO()
        handler = logging.StreamHandler(stream)
        handler.setFormatter(logging.Formatter("%(message)s"))
        filter_obj = SensitiveDataFilter()
        handler.addFilter(filter_obj)

        logger = logging.getLogger("test_adv_non_string_msg")
        logger.addHandler(handler)
        logger.setLevel(logging.INFO)

        logger.error(ValueError(f"Bad API call with key: {gemini_key}"))
        output = stream.getvalue()
        assert gemini_key not in output
        assert "[REDACTED_GEMINI_KEY]" in output

